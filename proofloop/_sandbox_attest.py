"""Signed result attestation for one pytest run inside the sandbox.

Loaded by the launcher via ``pytest.main(..., plugins=[...])``.  It writes a
compact JSON summary (collection count, nodeids, exit status) signed with an
HMAC key generated by the parent for this run.  The runner cross-checks that
summary against the junit report, so rewriting the junit file alone is not
enough to fake a verdict.

Same-process candidate code can still read the key from the environment; this
is a defence-in-depth measure, not a proof of isolation.
"""

import hashlib
import hmac
import json
import os
import time


def pytest_sessionstart(session):
    session._proofloop_started = time.time()


def pytest_sessionfinish(session, exitstatus):
    path = os.environ.get("PROOFLOOP_ATTEST_PATH")
    key = os.environ.get("PROOFLOOP_ATTEST_KEY")
    if not path or not key:
        return
    items = list(getattr(session, "items", []) or [])
    body = {
        "collected": len(items),
        "exitstatus": int(exitstatus),
        "nodeids": [getattr(item, "nodeid", "") for item in items],
        "ts": round(time.time(), 3),
    }
    payload = json.dumps(body, sort_keys=True, separators=(",", ":"))
    signature = hmac.new(key.encode(), payload.encode(), hashlib.sha256).hexdigest()
    try:
        with open(path, "w", encoding="utf-8") as fh:
            json.dump({"body": body, "sig": signature}, fh, sort_keys=True)
    except OSError:
        pass
